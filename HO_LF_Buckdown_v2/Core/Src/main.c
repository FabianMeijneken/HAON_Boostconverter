// A simple function which sets the duty cycle of timer 8 channel 1.
// @author Fabian Meijneken
// @param duty Specifies the desired duty cycle. This is expressed as a value between 0 and 1.
void set_PWM_duty(TIM_HandleTypeDef *htim, uint32_t channel, float duty)
{
    // Clamp the duty between 0 and 1 using ternary operators
    duty = (duty > 1.0f) ? 1.0f : duty;
    duty = (duty < 0.0f) ? 0.0f : duty;

    // Calculate the compare value dynamically using the timer instance's ARR
    __HAL_TIM_SET_COMPARE(htim, channel, (uint32_t)(htim->Instance->ARR * duty));
}

